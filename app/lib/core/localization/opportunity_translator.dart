          return 'সফটওয়্যার ইঞ্জিনিয়ারিং এবং কম্পিউটারে বিশেষ আগ্রহ।';
        case 'gu':
          return 'સોફ્ટવેર એન્જિનિયરિંગ અને કોમ્પ્યુટરમાં વિશેષ રસ.';
        case 'kn':
          return 'ಸಾಫ್ಟ್‌ವೇರ್ ಎಂಜಿನಿಯರಿಂಗ್ ಮತ್ತು ಕಂಪ್ಯೂಟರ್‌ನಲ್ಲಿ ಆಸಕ್ತಿ.';
