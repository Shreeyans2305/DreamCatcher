  /// Sanitize and localize profile education notes/descriptions
  static String sanitizeEducationDescription(String rawDescription, String langCode) {
    // Strip synthetic demographic pipe segments: Category: ... | Tribe: ... | Income: ...
    final parts = rawDescription.split('|').map((p) => p.trim()).where((p) {
      final lower = p.toLowerCase();
      return !lower.startsWith('category:') &&
          !lower.startsWith('tribe:') &&
          !lower.startsWith('disability:') &&
          !lower.startsWith('income:') &&
          !lower.startsWith('area:');
    }).toList();

    final remaining = parts.join(' ').trim();
    if (remaining.isEmpty) return '';

    final lowerRemaining = remaining.toLowerCase();
    if (lowerRemaining.contains('software engineering') || lowerRemaining.contains('computers')) {
      switch (langCode) {
        case 'mr':
          return 'सॉफ्टवेअर अभियांत्रिकी आणि संगणक तंत्रज्ञानामध्ये विशेष रस व आवड.';
        case 'hi':
          return 'सॉफ्टवेयर इंजीनियरिंग और कंप्यूटर प्रौद्योगिकी में विशेष रुचि।';
