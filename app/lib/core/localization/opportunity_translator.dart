  /// Translate opportunity title according to language code
  static String getTitle(String originalTitle, String langCode) {
    if (langCode == 'en') return originalTitle;
    final normalized = originalTitle.toLowerCase();
    for (final entry in _translations.entries) {
      if (normalized.contains(entry.key)) {
        final titleMap = entry.value['title'];
        if (titleMap != null && titleMap.containsKey(langCode)) {
          return titleMap[langCode]!;
        }
      }
    }
    return originalTitle;
  }

  /// Translate opportunity description according to language code
  static String? getDescription(String? originalDescription, String originalTitle, String langCode) {
    if (originalDescription == null) return null;
    if (langCode == 'en') return originalDescription;
    final normalized = originalTitle.toLowerCase();
    for (final entry in _translations.entries) {
      if (normalized.contains(entry.key)) {
        final descMap = entry.value['description'];
        if (descMap != null && descMap.containsKey(langCode)) {
          return descMap[langCode]!;
        }
      }
    }
    return originalDescription;
  }

  /// Translate opportunity type label
  static String getTypeLabel(String type, AppLocalizations l10n) {
    switch (type.toLowerCase()) {
      case 'scholarship':
        return l10n.opportunityTypeScholarship;
      case 'course':
        return l10n.opportunityTypeCourse;
      case 'entrance_exam':
        return l10n.opportunityTypeExam;
      case 'internship':
        return l10n.opportunityTypeInternship;
      default:
        return l10n.opportunityTypeGeneral;
    }
  }

  /// Format localized highlight benefit
  static String? getHighlightBenefit({
    required String type,
    double? amount,
    String? recurrence,
    double? stipend,
    String? duration,
    String? conductingBody,
    required AppLocalizations l10n,
    required String langCode,
  }) {
    if (amount != null && amount > 0) {
      final formatted = amount.toStringAsFixed(0);
      if (recurrence != null && recurrence.toLowerCase().contains('year') || recurrence == 'annual') {
        return l10n.perYearIncome(formatted);
      }
      return '₹$formatted ${recurrence ?? "award"}';
    }
    if (stipend != null && stipend > 0) {
      final formatted = stipend.toStringAsFixed(0);
      switch (langCode) {
        case 'hi':
          return '₹$formatted / माह वजीफा';
